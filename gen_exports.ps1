# Writes a header of linker /export forwarders that pass every export of
# C:\Windows\System32\<Dll>.dll through to the real system DLL.
# Needs dumpbin on PATH (run from a Visual Studio x64 developer prompt, as build.cmd does).
param(
    [Parameter(Mandatory)][string]$Dll,   # base name without .dll, e.g. dwmapi
    [Parameter(Mandatory)][string]$Out
)
$ErrorActionPreference = 'Stop'
$system = Join-Path $env:SystemRoot "System32\$Dll.dll"
if (-not (Test-Path $system)) { throw "$system not found" }

$target = ($env:SystemRoot + "\System32\$Dll") -replace '\\', '\\'
$lines = @(
    "// Generated by gen_exports.ps1 from $system. Do not edit."
    '#pragma once'
)
$count = 0
$inTable = $false
foreach ($row in (dumpbin /nologo /exports $system)) {
    if ($row -match '^\s+ordinal\s+hint\s+RVA\s+name') { $inTable = $true; continue }
    if (-not $inTable) { continue }
    if ($row -match '^\s*Summary') { break }
    # Rows look like one of:
    #   ord hint RVA      Name
    #   ord hint          Name (forwarded to X.Y)
    #   ord      RVA      [NONAME]
    if ($row -notmatch '^\s+(\d+)\s+(.*)$') { continue }
    $ord = $Matches[1]
    # Drop "(forwarded to ...)" and any "= InternalSymbol" suffix, leaving the export name last.
    $rest = $Matches[2] -replace '\s+\(forwarded to .*\)$', '' -replace '\s+=\s+.*$', ''
    $name = ($rest -split '\s+')[-1]
    if ($name -eq '[NONAME]') {
        $lines += "#pragma comment(linker, `"/export:__proxy_ord$ord=$target.#$ord,@$ord,NONAME`")"
    } else {
        $lines += "#pragma comment(linker, `"/export:$name=$target.$name,@$ord`")"
    }
    $count++
}
if ($count -eq 0) { throw "no exports parsed from $system" }
Set-Content -Path $Out -Value $lines -Encoding utf8
Write-Host "$Dll.dll: $count exports"
